const Ctx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({ lang: "en", t: en, setLang: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = localStorage.getItem("lang");
    if (saved === "ar" || saved === "en") setLangState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  const setLang = (l: Lang) => {
    localStorage.setItem("lang", l);
    setLangState(l);
  };
  return <Ctx.Provider value={{ lang, t: lang === "ar" ? ar : en, setLang }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);

export function useFormat() {
  const { lang } = useI18n();
  const locale = lang === "ar" ? "ar-JO-u-nu-latn" : "en-GB";
  return {
    dateTime: (iso: string) =>
      new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Amman" }).format(new Date(iso)),
    name: (u: { nameEn: string; nameAr: string }) => (lang === "ar" ? u.nameAr : u.nameEn),
  };
}
